/// What a calendar date marks.
enum CalendarDateKind {
  /// In cinemas.
  inCinemas,

  /// Digital release.
  digitalRelease,

  /// Physical release.
  physicalRelease,

  /// An episode airs.
  airDate,

  /// An album or book is released.
  releaseDate,

  /// A kind the app does not know.
  unknown,
}
